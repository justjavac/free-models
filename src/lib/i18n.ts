export type DictKey = keyof (typeof dictionaries)["zh"];

export function translate(locale: Locale, key: DictKey, vars?: Record<string, string | number>): string {
  let str: string = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return str;
}
